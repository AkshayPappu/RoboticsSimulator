"""
Plot telemetry data from CSV files generated by the simulator.

Usage:
    python plot_telemetry.py output/telemetry.csv
    python plot_telemetry.py output/run1.csv output/run2.csv --compare
"""

import argparse
import sys
from pathlib import Path

import numpy as np

try:
    import matplotlib.pyplot as plt
    HAS_MPL = True
except ImportError:
    HAS_MPL = False
    print("[plot] matplotlib not installed. Run: pip install matplotlib")


def load_telemetry(path: str) -> dict:
    """Load a telemetry CSV into a dictionary of numpy arrays."""
    data = np.genfromtxt(path, delimiter=",", names=True)
    return {name: data[name] for name in data.dtype.names}


def plot_trajectory(data: dict, title: str = "Robot Trajectory", save_path: str | None = None):
    """Plot the robot's XZ trajectory (top-down view)."""
    fig, ax = plt.subplots(figsize=(10, 8))
    ax.plot(data["pos_x"], data["pos_z"], "b-", linewidth=0.5)
    ax.plot(data["pos_x"][0], data["pos_z"][0], "go", markersize=10, label="Start")
    ax.plot(data["pos_x"][-1], data["pos_z"][-1], "rs", markersize=10, label="End")

    ax.set_xlabel("X (m)")
    ax.set_ylabel("Z (m)")
    ax.set_title(title)
    ax.legend()
    ax.set_aspect("equal")
    ax.grid(True, alpha=0.3)

    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()


def plot_speeds(data: dict, title: str = "Wheel Speeds", save_path: str | None = None):
    """Plot left and right wheel speeds over time."""
    fig, ax = plt.subplots(figsize=(12, 5))
    ax.plot(data["time"], data["left_wheel_speed"], label="Left Wheel", alpha=0.8)
    ax.plot(data["time"], data["right_wheel_speed"], label="Right Wheel", alpha=0.8)

    ax.set_xlabel("Time (s)")
    ax.set_ylabel("Speed (rad/s)")
    ax.set_title(title)
    ax.legend()
    ax.grid(True, alpha=0.3)

    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()


def plot_position(data: dict, title: str = "Position Over Time", save_path: str | None = None):
    """Plot X, Y, Z positions over time."""
    fig, axes = plt.subplots(3, 1, figsize=(12, 8), sharex=True)

    axes[0].plot(data["time"], data["pos_x"], "r-")
    axes[0].set_ylabel("X (m)")
    axes[0].grid(True, alpha=0.3)

    axes[1].plot(data["time"], data["pos_y"], "g-")
    axes[1].set_ylabel("Y (m)")
    axes[1].grid(True, alpha=0.3)

    axes[2].plot(data["time"], data["pos_z"], "b-")
    axes[2].set_ylabel("Z (m)")
    axes[2].set_xlabel("Time (s)")
    axes[2].grid(True, alpha=0.3)

    fig.suptitle(title)
    plt.tight_layout()

    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()


def plot_dashboard(data: dict, title: str = "Telemetry Dashboard", save_path: str | None = None):
    """Combined dashboard with trajectory, speeds, and position."""
    fig = plt.figure(figsize=(16, 10))

    # Trajectory (top-down)
    ax1 = fig.add_subplot(2, 2, 1)
    ax1.plot(data["pos_x"], data["pos_z"], "b-", linewidth=0.5)
    ax1.plot(data["pos_x"][0], data["pos_z"][0], "go", markersize=8, label="Start")
    ax1.plot(data["pos_x"][-1], data["pos_z"][-1], "rs", markersize=8, label="End")
    ax1.set_xlabel("X (m)")
    ax1.set_ylabel("Z (m)")
    ax1.set_title("Trajectory (Top-Down)")
    ax1.legend()
    ax1.set_aspect("equal")
    ax1.grid(True, alpha=0.3)

    # Height over time
    ax2 = fig.add_subplot(2, 2, 2)
    ax2.plot(data["time"], data["pos_y"], "g-")
    ax2.set_xlabel("Time (s)")
    ax2.set_ylabel("Y (m)")
    ax2.set_title("Height")
    ax2.grid(True, alpha=0.3)

    # Wheel speeds
    ax3 = fig.add_subplot(2, 2, 3)
    ax3.plot(data["time"], data["left_wheel_speed"], label="Left", alpha=0.8)
    ax3.plot(data["time"], data["right_wheel_speed"], label="Right", alpha=0.8)
    ax3.set_xlabel("Time (s)")
    ax3.set_ylabel("Speed (rad/s)")
    ax3.set_title("Wheel Speeds")
    ax3.legend()
    ax3.grid(True, alpha=0.3)

    # Heading
    ax4 = fig.add_subplot(2, 2, 4)
    ax4.plot(data["time"], np.degrees(data["heading"]), "m-")
    ax4.set_xlabel("Time (s)")
    ax4.set_ylabel("Heading (deg)")
    ax4.set_title("Heading")
    ax4.grid(True, alpha=0.3)

    fig.suptitle(title, fontsize=14)
    plt.tight_layout()

    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()


def compare_runs(paths: list[str], labels: list[str] | None = None, save_path: str | None = None):
    """Compare multiple telemetry runs on the same plot."""
    if labels is None:
        labels = [Path(p).stem for p in paths]

    fig, axes = plt.subplots(1, 2, figsize=(14, 6))

    for path, label in zip(paths, labels):
        data = load_telemetry(path)
        axes[0].plot(data["pos_x"], data["pos_z"], label=label, linewidth=0.8)

        speed = np.sqrt(data["vel_x"]**2 + data["vel_z"]**2)
        axes[1].plot(data["time"], speed, label=label, alpha=0.7)

    axes[0].set_xlabel("X (m)")
    axes[0].set_ylabel("Z (m)")
    axes[0].set_title("Trajectory Comparison")
    axes[0].legend()
    axes[0].set_aspect("equal")
    axes[0].grid(True, alpha=0.3)

    axes[1].set_xlabel("Time (s)")
    axes[1].set_ylabel("Speed (m/s)")
    axes[1].set_title("Speed Comparison")
    axes[1].legend()
    axes[1].grid(True, alpha=0.3)

    plt.tight_layout()

    if save_path:
        plt.savefig(save_path, dpi=150, bbox_inches="tight")
    plt.show()


def main():
    if not HAS_MPL:
        sys.exit(1)

    parser = argparse.ArgumentParser(description="Telemetry Plotter")
    parser.add_argument("files", nargs="+", help="Telemetry CSV file(s)")
    parser.add_argument("--plot", choices=["trajectory", "speeds", "position", "dashboard", "all"],
                        default="dashboard", help="Plot type")
    parser.add_argument("--compare", action="store_true",
                        help="Compare multiple runs side by side")
    parser.add_argument("--save", default=None, help="Save plot to file")
    parser.add_argument("--labels", nargs="*", help="Labels for comparison plots")

    args = parser.parse_args()

    if args.compare and len(args.files) > 1:
        compare_runs(args.files, args.labels, args.save)
        return

    for filepath in args.files:
        data = load_telemetry(filepath)
        name = Path(filepath).stem

        if args.plot in ("trajectory", "all"):
            plot_trajectory(data, f"{name} - Trajectory", args.save)
        if args.plot in ("speeds", "all"):
            plot_speeds(data, f"{name} - Wheel Speeds", args.save)
        if args.plot in ("position", "all"):
            plot_position(data, f"{name} - Position", args.save)
        if args.plot in ("dashboard", "all"):
            plot_dashboard(data, f"{name} - Dashboard", args.save)


if __name__ == "__main__":
    main()
